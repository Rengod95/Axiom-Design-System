const scalarSchemas = {
  string: { type: "string" }, boolean: { type: "boolean" }, integer: { type: "integer" },
  "nonnegative integer": { type: "integer", minimum: 0 }, "positive integer": { type: "integer", minimum: 1 },
  StableId: structuredClone(schema.properties.id), Revision: structuredClone(schema.properties.revision),
  // Identity/version syntax is an explicit bounded profile, not a namespace resolver or SemVer claim.
  NamespacedId: { type: "string", pattern: "\\S" }, Version: { type: "string", pattern: "\\S" },
  Kind: { type: "string", pattern: "\\S" }, DocumentKind: structuredClone(schema.properties.kind),
  record: { type: "object" },
};

function splitTopLevel(text, separator) {
  const parts = [];
  let start = 0, depth = 0;
  for (let index = 0; index < text.length; index++) {
    if (text[index] === "<") depth++;
    else if (text[index] === ">") depth--;
    else if (text[index] === separator && depth === 0) { parts.push(text.slice(start, index).trim()); start = index + 1; }
    if (depth < 0) throw new Error(`Invalid catalog type nesting: ${text}`);
  }
  if (depth !== 0) throw new Error(`Invalid catalog type nesting: ${text}`);
  parts.push(text.slice(start).trim());
  return parts;
}

function describeType(text, recordName, fieldName) {
  if (recordName === "RecordTypeExpr" && fieldName === "kind") return { kind: "enum", values: ["record"] };
  if (text === "parent-content-box") return { kind: "enum", values: [text] };
  if (LITERAL_UNIONS.has(text)) return { kind: "enum", values: text.split(" | ") };
  if (text === "null" || text === "unbounded") return { kind: "enum", values: [text === "null" ? null : text] };
  if (Object.hasOwn(scalarSchemas, text)) return { kind: "scalar", name: text };
  if (records.has(text)) return { kind: "record", name: text };
  const union = splitTopLevel(text, "|");
  if (union.length > 1) return { kind: "union", options: union.map(part => describeType(part)) };
  const list = /^(nonempty )?list<(.+)>$/.exec(text);
  if (list) return { kind: "array", nonempty: Boolean(list[1]), items: describeType(list[2]) };
  const map = /^map<(.+)>$/.exec(text);
  if (map) {
    const [keyType, values, ...remaining] = splitTopLevel(map[1], ",");
    if (!keyType || !values || remaining.length) throw new Error(`Invalid map type: ${text}`);
    return { kind: "map", keyType, values: describeType(values) };
  }
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(text)) throw new Error(`Unrecognized catalog type notation: ${text}`);
  return { kind: "opaque", name: text };
}

function schemaFor(shape) {
  switch (shape.kind) {
    case "scalar": return structuredClone(scalarSchemas[shape.name]);
    case "enum": return { enum: shape.values };
    case "record": return { $ref: `#/$defs/${shape.name}` };
    case "array": return { type: "array", items: schemaFor(shape.items), ...(shape.nonempty ? { minItems: 1 } : {}) };
    case "map": return { type: "object", additionalProperties: schemaFor(shape.values), $comment: `Map key meaning ${shape.keyType} is not interpreted by this profile.` };
    case "union": return { anyOf: shape.options.map(schemaFor) };
    case "opaque": return { ...(shape.name === "OpaqueExtensionMap" ? { type: "object" } : {}), $comment: `Unverified named type: ${shape.name}. Preserve without interpretation.` };
  }
  throw new Error("Unrecognized structural shape");
}

const metadata = {};
const definitions = {};
for (const record of records.values()) {
  const recordFields = record.fields.map(field => ({ ...field, shape: describeType(field.type, record.name, field.name) }));
  metadata[record.name] = { name: record.name, ownerDocumentId: record.ownerDocumentId, fields: recordFields };
  const definition = { type: "object", properties: Object.fromEntries(recordFields.map(field => [field.name, schemaFor(field.shape)])), required: recordFields.filter(field => field.required).map(field => field.name), additionalProperties: true, $comment: `Foundation ${record.ownerDocumentId} / ${record.name}; unresolved names are explicitly unverified.` };
  if (record.name === "DocumentEnvelope") definition.properties = structuredClone(schema.properties);
  definitions[record.name] = definition;
}
