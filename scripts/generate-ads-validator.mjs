import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { DOCUMENT_KINDS, ID_PATTERN, RESERVED_IDS } from "../modules/ads-core/src/constants.ts";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const SCHEMA_PATH = "modules/ads-core/schema/document-envelope.json";
const OUTPUT_PATH = "modules/ads-core/src/generated/document-envelope.ts";
const COMPILER_VERSION = "8.20.0";
const hash = (text) => createHash("sha256").update(text).digest("hex");
const schemaBytes = readFileSync(resolve(ROOT, SCHEMA_PATH));
const schema = JSON.parse(schemaBytes);
const pkg = JSON.parse(readFileSync(resolve(ROOT, "node_modules/ajv/package.json"), "utf8"));
if (pkg.version !== COMPILER_VERSION) throw new Error("Unexpected schema compiler version");
if (schema.properties.id.pattern !== ID_PATTERN.source || schema.properties.revision.pattern !== ID_PATTERN.source
  || JSON.stringify(schema.properties.kind.enum) !== JSON.stringify([...DOCUMENT_KINDS])
  || JSON.stringify(schema.properties.id.not.enum) !== JSON.stringify([...RESERVED_IDS])
  || JSON.stringify(schema.properties.revision.not.enum) !== JSON.stringify([...RESERVED_IDS])) throw new Error("Schema identity projection drift");
const catalog = JSON.parse(readFileSync(resolve(ROOT, "docs/foundation/annexes/field-catalog.json"), "utf8"));
const fields = catalog.records.find((record) => record.name === "DocumentEnvelope").fields;
if (JSON.stringify(fields.filter((field) => field.required).map((field) => field.name)) !== JSON.stringify(schema.required)
  || JSON.stringify(fields.map((field) => field.name)) !== JSON.stringify(Object.keys(schema.properties))) throw new Error("Foundation envelope field projection drift");
const ajv = new Ajv2020({ strict: true, allErrors: true, ownProperties: true, code: { source: true, esm: true, lines: true }, coerceTypes: false, useDefaults: false, removeAdditional: false });
const compiled = standaloneCode(ajv, ajv.compile(schema)).trimEnd();
if (/\b(?:require|eval|Function)\s*\(|\bimport\s/.test(compiled)) throw new Error("Generated validator has an unapproved runtime dependency or evaluation");
const scriptDigest = hash(readFileSync(fileURLToPath(import.meta.url)));
const output = `// @ts-nocheck -- generated JavaScript body; strict wrapper and standalone conformance tests own the boundary.\n// GENERATED by scripts/generate-ads-validator.mjs; DO NOT EDIT.\n// Ajv ${COMPILER_VERSION} (MIT); see docs/implementation/schema-compiler-notice.md.\n// Schema ${SCHEMA_PATH}; sha256=${hash(schemaBytes)}\n// Generator sha256=${scriptDigest}; dialect=2020-12; canonical-profile=1.0.0\n${compiled}\n`;
const destination = resolve(ROOT, OUTPUT_PATH);
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) throw new Error("Generated envelope validator drift; run pnpm generate and review");
  console.log("Generated envelope schema is current; Foundation field and identity projections match");
} else {
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, output, "utf8");
  console.log(`Generated ${OUTPUT_PATH}`);
}
